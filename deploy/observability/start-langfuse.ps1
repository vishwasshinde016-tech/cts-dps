# Starts Langfuse (DPS traces) on this laptop and points DPS at it. Windows PowerShell 5.1 or 7.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File deploy\observability\start-langfuse.ps1
#   ... -Port 3100          use another port when 3000 is taken
#   ... -NoDpsEnv           start Langfuse only; leave dps\.env as it is
#
# What it does, in order:
#   1. finds Docker and starts Docker Desktop if the engine is not running (waits up to 3 minutes);
#   2. first run only: writes deploy\observability\.env with random secrets, the DPS project's keys and a sign-in user
#      (git-ignored; never printed except the sign-in user);
#   3. loads the images from images\langfuse-images.tar when that file is there (offline laptops), else Docker pulls;
#   4. starts the stack (docker-compose.langfuse.yml), all ports on 127.0.0.1;
#   5. waits for http://127.0.0.1:<port>/api/public/health;
#   6. writes the OTEL_* lines into dps\.env so the DPS API and worker send their traces to it.
# Nothing is sent outside this laptop: Langfuse telemetry is off, and DPS sends traces to 127.0.0.1 only.

param(
    [int]$Port = 3000,
    [switch]$NoDpsEnv
)

# "Continue", not "Stop": Docker writes its progress to stderr, which Windows PowerShell 5.1 turns into a
# script-stopping error under "Stop". Every docker call is checked with $LASTEXITCODE instead.
$ErrorActionPreference = "Continue"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent (Split-Path -Parent $here)
$compose = Join-Path $here "docker-compose.langfuse.yml"
$envFile = Join-Path $here ".env"
$bundle = Join-Path $here "images\langfuse-images.tar"
$dpsEnv = Join-Path $root "dps\.env"

function Step($text) { Write-Host ""; Write-Host "=== $text" -ForegroundColor Cyan }
function Fail($text) { Write-Host "LANGFUSE NOT STARTED: $text" -ForegroundColor Red; exit 1 }

function New-Secret([int]$bytes) {
    $buffer = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    return -join ($buffer | ForEach-Object { $_.ToString("x2") })
}

function Find-Docker {
    $cmd = Get-Command docker -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $candidates = @(
        (Join-Path $env:LOCALAPPDATA "Programs\DockerDesktop\resources\bin\docker.exe"),
        (Join-Path $env:ProgramFiles "Docker\Docker\resources\bin\docker.exe")
    )
    foreach ($c in $candidates) { if (Test-Path $c) { return $c } }
    return $null
}

function Test-Engine($docker) {
    & $docker info --format "{{.ServerVersion}}" 2>&1 | Out-Null
    return ($LASTEXITCODE -eq 0)
}

Step "1. Docker"
$docker = Find-Docker
if (-not $docker) { Fail "Docker is not installed. Install Docker Desktop (or ask IT), then run this again." }
if (-not (Test-Engine $docker)) {
    $desktop = @(
        (Join-Path $env:LOCALAPPDATA "Programs\DockerDesktop\Docker Desktop.exe"),
        (Join-Path $env:ProgramFiles "Docker\Docker\Docker Desktop.exe")
    ) | Where-Object { Test-Path $_ } | Select-Object -First 1
    if (-not $desktop) { Fail "the Docker engine is not running and Docker Desktop was not found: start Docker yourself." }
    Write-Host "starting Docker Desktop ..."
    Start-Process -FilePath $desktop | Out-Null
    $deadline = (Get-Date).AddMinutes(3)
    while (-not (Test-Engine $docker)) {
        if ((Get-Date) -gt $deadline) { Fail "Docker Desktop did not start within 3 minutes." }
        Start-Sleep -Seconds 5
    }
}
Write-Host ("docker engine " + (& $docker info --format "{{.ServerVersion}}"))

Step "2. Secrets (deploy\observability\.env)"
if (Test-Path $envFile) {
    Write-Host ".env already exists: kept (delete it and the volumes to start from scratch)"
} else {
    $lines = @(
        "# Generated by start-langfuse.ps1 on $(Get-Date -Format s). Git-ignored. Do not share.",
        "LANGFUSE_PORT=$Port",
        "SALT=$(New-Secret 32)",
        "ENCRYPTION_KEY=$(New-Secret 32)",
        "NEXTAUTH_SECRET=$(New-Secret 32)",
        "POSTGRES_PASSWORD=$(New-Secret 16)",
        "CLICKHOUSE_PASSWORD=$(New-Secret 16)",
        "REDIS_AUTH=$(New-Secret 16)",
        "MINIO_ROOT_PASSWORD=$(New-Secret 16)",
        "LANGFUSE_PUBLIC_KEY=pk-lf-$(New-Secret 16)",
        "LANGFUSE_SECRET_KEY=sk-lf-$(New-Secret 16)",
        "LANGFUSE_USER_EMAIL=demo@cts-dps.local",
        "LANGFUSE_USER_PASSWORD=$(New-Secret 10)"
    )
    Set-Content -Path $envFile -Value $lines -Encoding ASCII
    Write-Host ".env written with new random secrets"
}
$cfg = @{}
foreach ($line in Get-Content $envFile) {
    if ($line -match '^\s*([A-Z_]+)=(.*)$') { $cfg[$Matches[1]] = $Matches[2].Trim() }
}
if ($cfg.ContainsKey("LANGFUSE_PORT")) { $Port = [int]$cfg["LANGFUSE_PORT"] }

Step "3. Images"
if (Test-Path $bundle) {
    Write-Host "loading images from $bundle (offline bundle) ..."
    & $docker load -i $bundle
    if ($LASTEXITCODE -ne 0) { Fail "docker load failed for $bundle" }
} else {
    Write-Host "no offline bundle: Docker pulls the images it does not have (needs internet once)"
}

Step "4. Start the stack"
& $docker compose -f $compose --env-file $envFile up -d
if ($LASTEXITCODE -ne 0) { Fail "docker compose up failed (see above). Is port $Port free? Use -Port 3100." }

Step "5. Wait until Langfuse answers"
$health = "http://127.0.0.1:$Port/api/public/health"
$deadline = (Get-Date).AddMinutes(6)
$ok = $false
while ((Get-Date) -lt $deadline) {
    try {
        $r = Invoke-WebRequest -Uri $health -UseBasicParsing -TimeoutSec 5
        if ($r.StatusCode -eq 200) { $ok = $true; break }
    } catch { }
    Start-Sleep -Seconds 5
}
if (-not $ok) { Fail "Langfuse did not answer on $health within 6 minutes. See: docker compose -f `"$compose`" logs langfuse-web" }
Write-Host "Langfuse is up: http://localhost:$Port" -ForegroundColor Green

Step "6. Point DPS at Langfuse (dps\.env)"
$pair = "$($cfg['LANGFUSE_PUBLIC_KEY']):$($cfg['LANGFUSE_SECRET_KEY'])"
$basic = [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes($pair))
$otel = @(
    "OTEL_EXPORTER_OTLP_TRACES_ENDPOINT=http://127.0.0.1:$Port/api/public/otel/v1/traces",
    "OTEL_EXPORTER_OTLP_TRACES_PROTOCOL=http/protobuf",
    "OTEL_EXPORTER_OTLP_TRACES_HEADERS=Authorization=Basic%20$basic,x-langfuse-ingestion-version=4"
)
if ($NoDpsEnv) {
    Write-Host "-NoDpsEnv: dps\.env left as it is. To send DPS traces here, add these lines to dps\.env:"
    $otel | ForEach-Object { Write-Host "  $_" }
} elseif (-not (Test-Path $dpsEnv)) {
    Write-Host "dps\.env does not exist yet (run dps\scripts\setup.ps1 first); the lines to add are:" -ForegroundColor Yellow
    $otel | ForEach-Object { Write-Host "  $_" }
} else {
    $kept = Get-Content $dpsEnv | Where-Object { $_ -notmatch '^\s*OTEL_' -and $_ -notmatch '^# Traces to Langfuse' }
    $new = $kept + @("# Traces to Langfuse on this laptop (written by start-langfuse.ps1)") + $otel
    # UTF-8 without a byte-order mark: Windows PowerShell 5.1 adds one with -Encoding UTF8, and it would spoil
    # the first key of dps.env.
    [System.IO.File]::WriteAllLines($dpsEnv, [string[]]$new, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "dps\.env: OTEL_* lines written; restart the DPS API and worker to start sending traces"
}

Write-Host ""
Write-Host "Langfuse:  http://localhost:$Port" -ForegroundColor Green
Write-Host "Sign in:   $($cfg['LANGFUSE_USER_EMAIL'])  (password: LANGFUSE_USER_PASSWORD in deploy\observability\.env)"
Write-Host "Project:   CTS DPS  ->  Tracing"
Write-Host "Stop:      powershell -ExecutionPolicy Bypass -File deploy\observability\stop-langfuse.ps1"
